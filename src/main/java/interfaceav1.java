private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
    try {
        double lado1 = Double.parseDouble(jTextArea1.getText().trim());
        double lado2 = Double.parseDouble(jTextArea2.getText().trim());
        double lado3 = Double.parseDouble(jTextArea3.getText().trim());
        if (lado1 <= 0 || lado2 <= 0 || lado3 <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Os lados devem ser maiores que zero!"
            );
            return;
        }
        if (lado1 + lado2 <= lado3 ||
            lado1 + lado3 <= lado2 ||
            lado2 + lado3 <= lado1) {

            javax.swing.JOptionPane.showMessageDialog(
                this, "Esses valores não formam um triângulo!"
            );
            return;
        }
        String tipo;

        if (lado1 == lado2 && lado2 == lado3) {
            tipo = "Triângulo Equilátero";
        } else if (lado1 == lado2 ||
                   lado1 == lado3 ||
                   lado2 == lado3) {
            tipo = "Triângulo Isósceles";
        } else {
            tipo = "Triângulo Escaleno";
        }
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Tipo: " + tipo +
            "\nLado 1: " + lado1 +
            "\nLado 2: " + lado2 +
            "\nLado 3: " + lado3
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Digite valores numéricos válidos nos três lados!"
        );
    }
}

